import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR.parent / ".env")
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
DB_PATH = Path(os.environ.get("PHISHGUARD_DB_PATH", BASE_DIR / "instance" / "phishguard.db"))

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:
    psycopg = None
    dict_row = None

DB_INTEGRITY_ERRORS = (sqlite3.IntegrityError,) + (
    (psycopg.IntegrityError,) if psycopg else ()
)

if not DATABASE_URL:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    @staticmethod
    def _translate(sql):
        return (
            sql.replace("datetime('now', ?)", "(timezone('UTC', CURRENT_TIMESTAMP) + (%s)::interval)")
            .replace("date('now')", "CURRENT_DATE")
            .replace("?", "%s")
        )

    def execute(self, sql, parameters=()):
        return self.connection.execute(self._translate(sql), parameters)

    def executemany(self, sql, parameters):
        return self.connection.executemany(self._translate(sql), parameters)


@contextmanager
def get_db():
    if DATABASE_URL:
        if psycopg is None:
            raise RuntimeError("Install the psycopg dependency to use DATABASE_URL.")
        connection = psycopg.connect(
            DATABASE_URL,
            connect_timeout=10,
            row_factory=dict_row,
        )
        try:
            with connection:
                yield PostgresConnection(connection)
        finally:
            connection.close()
        return

    connection = sqlite3.connect(DB_PATH, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    try:
        with connection:
            yield connection
    finally:
        connection.close()


def _init_sqlite(db):
    db.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL
        )
    """)
    user_columns = {row["name"] for row in db.execute("PRAGMA table_info(users)")}
    if "created_at" not in user_columns:
        db.execute("ALTER TABLE users ADD COLUMN created_at TIMESTAMP")
    if "session_version" not in user_columns:
        db.execute("ALTER TABLE users ADD COLUMN session_version INTEGER NOT NULL DEFAULT 0")

    db.execute("""
        CREATE TABLE IF NOT EXISTS scans (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            url TEXT NOT NULL,
            result TEXT NOT NULL,
            risk_score INTEGER NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            signals_json TEXT NOT NULL DEFAULT '[]',
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    """)
    scan_columns = {row["name"] for row in db.execute("PRAGMA table_info(scans)")}
    if "signals_json" not in scan_columns:
        db.execute("ALTER TABLE scans ADD COLUMN signals_json TEXT NOT NULL DEFAULT '[]'")

    _normalize_scan_labels(db)
    db.execute("CREATE INDEX IF NOT EXISTS idx_scans_user_id_id ON scans(user_id, id DESC)")
    db.execute("""
        CREATE TABLE IF NOT EXISTS password_reset_tokens (
            user_id INTEGER PRIMARY KEY,
            token_hash TEXT UNIQUE NOT NULL,
            expires_at TEXT NOT NULL,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS user_settings (
            user_id INTEGER PRIMARY KEY,
            preferences_json TEXT NOT NULL,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
    """)


def _init_postgres(db):
    db.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            created_at TIMESTAMP WITHOUT TIME ZONE,
            session_version INTEGER NOT NULL DEFAULT 0
        )
    """)
    db.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE")
    db.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0")
    db.execute("""
        CREATE TABLE IF NOT EXISTS scans (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            url TEXT NOT NULL,
            result TEXT NOT NULL,
            risk_score INTEGER NOT NULL,
            created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('UTC', CURRENT_TIMESTAMP),
            signals_json TEXT NOT NULL DEFAULT '[]'
        )
    """)
    db.execute("ALTER TABLE scans ADD COLUMN IF NOT EXISTS signals_json TEXT NOT NULL DEFAULT '[]'")
    _normalize_scan_labels(db)
    db.execute("CREATE INDEX IF NOT EXISTS idx_scans_user_id_id ON scans(user_id, id DESC)")
    db.execute("""
        CREATE TABLE IF NOT EXISTS password_reset_tokens (
            user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
            token_hash TEXT UNIQUE NOT NULL,
            expires_at TEXT NOT NULL
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS user_settings (
            user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
            preferences_json TEXT NOT NULL
        )
    """)


def _normalize_scan_labels(db):
    db.execute("""
        UPDATE scans
        SET result = CASE
            WHEN risk_score >= 60 THEN 'malicious'
            WHEN risk_score >= 30 THEN 'phishing'
            ELSE 'safe'
        END
        WHERE result IN ('likely_legitimate', 'suspicious', 'phishing')
    """)


def init_db():
    with get_db() as db:
        if DATABASE_URL:
            _init_postgres(db)
        else:
            _init_sqlite(db)
    print("Database ready: PostgreSQL" if DATABASE_URL else f"Database ready: {DB_PATH}")


if __name__ == "__main__":
    init_db()
